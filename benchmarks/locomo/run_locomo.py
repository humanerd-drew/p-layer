#!/usr/bin/env python3
"""LoCoMo adapter for p-layer (Snap Research, ACL 2024).

Two-party long-conversation memory benchmark. 10 conversations, 1,986 QA,
5 categories (1 single-hop, 2 multi-hop, 3 temporal, 4 commonsense/world
knowledge, 5 adversarial). Evidence labels ("D<session>:<turn>") let us score
retrieval offline, with zero LLM calls:

  ingest  -> per-conversation isolated Store; every turn (both speakers) is a
             governed knowledge row keyed by its dia_id
  recall  -> p-layer recall (shipped path) for each question
  metrics -> evidence recall@k / MRR (evidence turn in top-k), by category;
             adversarial (cat 5) reported separately (correct behavior there
             is refusal, not retrieval)

Optional QA lane (--generate): answers are generated by an explicitly named
model only — never substituted — and written as hypothesis.jsonl for the
official LoCoMo evaluator. Like the LongMemEval adapter, the model for QA is
a harness contract decision and is gated (no implicit default).

Usage:
  python3 run_locomo.py --data data/locomo10.json --k 10 --embedder hash
  python3 run_locomo.py --data data/locomo10.json --generate --model <explicit-model>
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from p_layer.embed import load_embedder  # noqa: E402
from p_layer.store import Store  # noqa: E402

DIA_RE = re.compile(r"D(\d+):(\d+)")


def _iter_turns(conversation: dict):
    """Yield (session_name, dia_id, speaker, text) for every turn."""
    for key, value in conversation.items():
        if key.startswith("session_") and isinstance(value, list):
            for turn in value:
                yield key, turn.get("dia_id", ""), turn.get("speaker", ""), turn.get("text", "")


def ingest_conversation(store: Store, conversation: dict, layer: str) -> dict:
    """Write every turn into the store; return dia_id -> knowledge row id."""
    dia_to_kid: dict[str, int] = {}
    for sess, dia, speaker, text in _iter_turns(conversation):
        if not text.strip():
            continue
        content = text  # both speakers are conversation partners, keep verbatim
        kid = store.add_knowledge(
            content=content,
            type="fact",
            session_id=sess,
            layer=layer,
            who="system",
        )
        dia_to_kid[dia] = kid
    return dia_to_kid


def evidence_dia_ids(evidence: list[str]) -> set[str]:
    out = set()
    for ev in evidence:
        m = DIA_RE.match(ev)
        if m:
            out.add(f"D{int(m.group(1))}:{int(m.group(2))}")
    return out


def evaluate_question(store: Store, dia_to_kid: dict, qa: dict, k: int,
                      baseline: str) -> dict:
    rows = store.recall(qa["question"], limit=k) if baseline == "hybrid" else [
        dict(r) for r in store.fts_search(qa["question"], limit=k)]
    evidence = evidence_dia_ids(qa.get("evidence") or [])
    kid_to_dia = {v: kk for kk, v in dia_to_kid.items()}
    hits = [rank for rank, row in enumerate(rows, start=1)
            if kid_to_dia.get(row["id"]) in evidence]
    return {
        "question": qa["question"][:80],
        "category": qa.get("category"),
        "adversarial": qa.get("category") == 5,
        "n_evidence": len(evidence),
        "recall_at_k": 1 if hits else 0,
        "mrr": 1.0 / hits[0] if hits else 0.0,
        "n_retrieved": len(rows),
        "n_hits": len(hits),
    }


def chat_once(model: str, query: str, context: str) -> str:
    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        raise SystemExit("--generate requires OPENAI_API_KEY")
    base = os.environ.get("OPENAI_BASE_URL", "https://api.openai.com/v1").rstrip("/")
    body = json.dumps({
        "model": model,
        "messages": [
            {"role": "system", "content": (
                "Answer the question based ONLY on the retrieved conversation "
                "memory below. If the answer cannot be determined, reply exactly: "
                "I don't know.")},
            {"role": "user", "content": f"Retrieved memory:\n{context or '(none)'}\n\nQuestion: {query}"},
        ],
        "temperature": 0,
    }).encode("utf-8")
    last_err = None
    for attempt in range(8):
        req = urllib.request.Request(
            f"{base}/chat/completions", data=body,
            headers={"Content-Type": "application/json",
                     "Authorization": f"Bearer {api_key}"})
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                data = json.loads(resp.read())
            return data["choices"][0]["message"]["content"].strip()
        except urllib.error.HTTPError as exc:
            last_err = exc
            if exc.code in (429, 500, 502, 503, 504):
                time.sleep(min(2 ** attempt, 60))
                continue
            raise
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            last_err = exc
            time.sleep(min(2 ** attempt, 60))
    raise RuntimeError(f"chat_once failed after retries: {last_err}")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", default=str(Path(__file__).parent / "data" / "locomo10.json"))
    p.add_argument("--out", default="./locomo-out")
    p.add_argument("--k", type=int, default=10)
    p.add_argument("--embedder", default="hash", choices=["hash", "ollama", "none"])
    p.add_argument("--layer", default="P2")
    p.add_argument("--baseline", default="hybrid", choices=["hybrid", "fts"])
    p.add_argument("--max-convs", type=int, default=0, help="0 = all 10")
    p.add_argument("--generate", action="store_true")
    p.add_argument("--model", default=None,
                   help="QA model — explicitly required, never substituted")
    args = p.parse_args(argv)
    if args.generate and not args.model:
        raise SystemExit("REFUSED: --generate requires an explicit --model (no substitution).")

    with open(args.data, encoding="utf-8") as fh:
        dataset = json.load(fh)
    convs = dataset[: args.max_convs] if args.max_convs else dataset
    print(f"[locomo] {len(convs)} conversations | k={args.k} embedder={args.embedder}")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="locomo-"))
    embedder = load_embedder(args.embedder)

    all_results: list[dict] = []
    hypotheses: list[dict] = []
    for ci, conv in enumerate(convs, start=1):
        db_path = tmp / f"conv{ci}.db"
        store = Store(db_path, embedder=embedder)
        try:
            dia_to_kid = ingest_conversation(store, conv["conversation"], args.layer)
            n_turns = len(dia_to_kid)
            qa_list = conv.get("qa", [])
            for qa in qa_list:
                res = evaluate_question(store, dia_to_kid, qa, args.k, args.baseline)
                all_results.append(res)
                if args.generate:
                    rows = store.recall(qa["question"], limit=args.k)
                    context = "\n".join(
                        f"[{r.get('session_id', '?')}] {r['content']}" for r in rows)
                    hypotheses.append({"question": qa["question"],
                                       "answer": chat_once(args.model, qa["question"], context)})
        finally:
            store.close()
        print(f"  [{ci}/{len(convs)}] {conv['sample_id']} turns={n_turns} qa={len(qa_list)}")

    scored = [r for r in all_results if not r["adversarial"]]
    adv = [r for r in all_results if r["adversarial"]]
    n = len(scored) or 1
    summary = {
        "config": {"k": args.k, "embedder": args.embedder, "layer": args.layer,
                   "baseline": args.baseline, "conversations": len(convs),
                   "questions": len(all_results)},
        "n_scored": len(scored),
        "n_adversarial": len(adv),
        "evidence_recall_at_k": sum(r["recall_at_k"] for r in scored) / n,
        "evidence_mrr": sum(r["mrr"] for r in scored) / n,
        "by_category": {},
    }
    for cat in sorted({r["category"] for r in scored}):
        rows = [r for r in scored if r["category"] == cat]
        summary["by_category"][str(cat)] = {
            "n": len(rows),
            "evidence_recall_at_k": sum(r["recall_at_k"] for r in rows) / len(rows),
        }

    with open(out / "evidence_results.jsonl", "w", encoding="utf-8") as fh:
        for r in all_results:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(out / "summary.json", "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=2, ensure_ascii=False)
    if hypotheses:
        with open(out / "hypothesis.jsonl", "w", encoding="utf-8") as fh:
            for h in hypotheses:
                fh.write(json.dumps(h, ensure_ascii=False) + "\n")

    print(f"[summary] evidence recall@{args.k}: {summary['evidence_recall_at_k']:.4f} "
          f"| mrr: {summary['evidence_mrr']:.4f} | n={len(scored)} (adv excluded: {len(adv)})")
    for cat, v in summary["by_category"].items():
        print(f"  category {cat}: recall@{args.k} {v['evidence_recall_at_k']:.4f} (n={v['n']})")
    print(f"[out] {out}/summary.json evidence_results.jsonl")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
